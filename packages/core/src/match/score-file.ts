/**
 * 比分文件的地址：scores/<比赛 id 的 SHA-256 前 24 位十六进制>.json。
 *
 * 比赛 id 里有两队的名字（淘汰赛还有轮次），直接用作文件名的话，公开的部署日志
 * （上传网页时会列出所有文件）和网址里就能看出谁打进了下一轮。换成哈希后文件名里没有队名；
 * 网页、插件、用户脚本都知道比赛 id，自己算出同样的文件名去下载。
 *
 * 这不是加密：只是不让文件名本身泄露对阵。比分内容仍然只在用户确认后才下载。
 * 用纯 JS 实现（同步），不依赖 crypto.subtle：用户脚本可能运行在 http 页面上，那里没有 crypto.subtle。
 */
export function scoreFileName(matchId: string): string {
  return sha256Hex(`sff-score:${matchId}`).slice(0, 24);
}

/** 相对数据目录的比分文件路径 */
export function scorePath(matchId: string): string {
  return `scores/${scoreFileName(matchId)}.json`;
}

